// ============================================================================
// THEMATIC COLOR & ICON RESOLVER
// ============================================================================

const getServicePresentation = (name = "", iconClass = "") => {
  const n = (name || "").toLowerCase();
  const c = (iconClass || "").toLowerCase();

  // 1. Tax & Finance: Soft Amber/Emerald
  if (n.includes("property tax") || c.includes("property-tax")) {
    return {
      categoryClass: "mseva-cat-tax-finance bg-emerald-50 text-emerald-600 border border-emerald-100",
      icon: <PropertyTaxIcon />,
    };
  }
  if (n.includes("challan") || c.includes("challan")) {
    return {
      categoryClass: "mseva-cat-tax-finance bg-emerald-50 text-emerald-600 border border-emerald-100",
      icon: <ChallanIcon />,
    };
  }
  if (n.includes("rent") || n.includes("lease") || c.includes("rent")) {
    return {
      categoryClass: "mseva-cat-tax-finance bg-emerald-50 text-emerald-600 border border-emerald-100",
      icon: <RentLeaseIcon />,
    };
  }
  if (n.includes("misc") || n.includes("collection") || c.includes("misc") || c.includes("mcollect")) {
    return {
      categoryClass: "mseva-cat-tax-finance bg-emerald-50 text-emerald-600 border border-emerald-100",
      icon: <MiscCollectionsIcon />,
    };
  }

  // 2. Public Utilities & Water: Soft Cyan
  if (n.includes("water") || n.includes("sewerage") || c.includes("water")) {
    return {
      categoryClass: "mseva-cat-utilities bg-cyan-50 text-cyan-600 border border-cyan-100",
      icon: <WaterIcon />,
    };
  }
  if (n.includes("garbage") || n.includes("waste") || c.includes("garbage") || c.includes("swach")) {
    return {
      categoryClass: "mseva-cat-utilities bg-cyan-50 text-cyan-600 border border-cyan-100",
      icon: <GarbageIcon />,
    };
  }

  // 3. Grievances & Pet: Soft Violet/Rose
  if (n.includes("grievance") || c.includes("grievance") || c.includes("pgr")) {
    return {
      categoryClass: "mseva-cat-grievances bg-purple-50 text-purple-600 border border-purple-100",
      icon: <GrievanceIcon />,
    };
  }
  if (n.includes("survey") || c.includes("survey")) {
    return {
      categoryClass: "mseva-cat-grievances bg-purple-50 text-purple-600 border border-purple-100",
      icon: <SurveyIcon />,
    };
  }
  if (n.includes("pet") || c.includes("pet") || c.includes("ptr")) {
    return {
      categoryClass: "mseva-cat-grievances bg-purple-50 text-purple-600 border border-purple-100",
      icon: <PetIcon />,
    };
  }

  // 4. Approvals, NOC & Civic: Soft Blue/Navy
  if (n.includes("trade") || n.includes("license") || c.includes("trade") || c.includes("tl")) {
    return {
      categoryClass: "mseva-cat-civic-approvals bg-blue-50 text-[#184474] border border-blue-100",
      icon: <TradeLicenseIcon />,
    };
  }
  if (n.includes("building") || n.includes("bpa") || n.includes("obps") || c.includes("building") || c.includes("obps")) {
    return {
      categoryClass: "mseva-cat-civic-approvals bg-blue-50 text-[#184474] border border-blue-100",
      icon: <BuildingPlanIcon />,
    };
  }
  if (n.includes("no dues") || n.includes("ndc") || c.includes("ndc")) {
    return {
      categoryClass: "mseva-cat-civic-approvals bg-blue-50 text-[#184474] border border-blue-100",
      icon: <NoDuesIcon />,
    };
  }
  if (n.includes("plot") || n.includes("regularisation") || c.includes("plot")) {
    return {
      categoryClass: "mseva-cat-civic-approvals bg-blue-50 text-[#184474] border border-blue-100",
      icon: <PlotRegularisationIcon />,
    };
  }
  if (n.includes("fire") || c.includes("fire")) {
    return {
      categoryClass: "mseva-cat-civic-approvals bg-blue-50 text-[#184474] border border-blue-100",
      icon: <FireNocIcon />,
    };
  }
  if (n.includes("vending") || n.includes("street") || c.includes("vending")) {
    return {
      categoryClass: "mseva-cat-civic-approvals bg-blue-50 text-[#184474] border border-blue-100",
      icon: <StreetVendingIcon />,
    };
  }
  if (n.includes("advertisement") || n.includes("hoarding") || c.includes("ads")) {
    return {
      categoryClass: "mseva-cat-civic-approvals bg-blue-50 text-[#184474] border border-blue-100",
      icon: <AdvertisementIcon />,
    };
  }
  if (n.includes("venue") || n.includes("chb") || n.includes("hall") || c.includes("venue") || c.includes("chb")) {
    return {
      categoryClass: "mseva-cat-civic-approvals bg-blue-50 text-[#184474] border border-blue-100",
      icon: <VenueBookingIcon />,
    };
  }

  // Fallback
  return {
    categoryClass: "mseva-cat-civic-approvals bg-blue-50 text-[#184474] border border-blue-100",
    icon: <DefaultCivicIcon />,
  };
};

// ============================================================================
// REDESIGNED OPTION CARD COMPONENT
// ============================================================================

const Option = ({ name, Icon, iconClass, onClick, className }) => {
  const { categoryClass, icon: vectorIcon } = getServicePresentation(name, iconClass);

  return (
    <button
      type="button"
      className={`mseva-service-card group relative flex flex-col justify-between p-4 sm:p-5 min-h-[135px] bg-white rounded-2xl border border-slate-200/80 shadow-xs hover:shadow-xl hover:shadow-blue-900/10 hover:border-blue-400/60 hover:-translate-y-1.5 active:scale-[0.98] transition-all duration-200 ease-out cursor-pointer text-left focus:outline-none focus:ring-2 focus:ring-blue-500/20 ${className || ""}`}
      onClick={onClick}
    >
      {/* Top Row: Squircle Vector Icon Container + Diagonal Hover Arrow */}
      <div className="mseva-card-top-row flex items-center justify-between w-full">
        <div className={`mseva-card-squircle w-11 h-11 rounded-xl flex items-center justify-center transition-transform duration-200 ease-out group-hover:scale-110 group-hover:rotate-1 ${categoryClass}`}>
          {vectorIcon || Icon}
        </div>

        {/* Subtle diagonal arrow indicator that shifts on hover */}
        <span className="mseva-card-arrow-indicator opacity-0 group-hover:opacity-100 -translate-x-1 translate-y-1 group-hover:translate-x-0 group-hover:translate-y-0 text-blue-500 transition-all duration-200 ease-out">
          <ArrowUpRight />
        </span>
      </div>

      {/* Bottom Row: Verbatim Service Title (Case, spelling & phrasing strictly preserved) */}
      <div className="mt-3.5 w-full">
        <span className="mseva-card-title-text text-xs sm:text-sm font-semibold text-slate-800 text-left transition-colors duration-150 group-hover:text-[#184474] leading-snug line-clamp-2 block">
          {name}
        </span>
      </div>
    </button>
  );
};

